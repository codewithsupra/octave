import net from "node:net";

export interface PortBlock {
  base: number;
  ports: number[];
}

export type PortProbe = (port: number) => Promise<boolean>;

/** True when nothing is listening on the port (IPv4 + IPv6 loopback/any). */
export const isPortFree: PortProbe = (port) =>
  new Promise((resolve) => {
    const srv = net.createServer();
    srv.unref();
    srv.once("error", () => resolve(false));
    srv.listen({ port, host: "::", ipv6Only: false }, () => srv.close(() => resolve(true)));
  });

/**
 * Hands each workspace a contiguous block of ports that is (a) not reserved by
 * another workspace and (b) not currently bound by anything else on the box.
 * Fixes "ten agents all trying to start a dev server on :3000".
 */
export class PortAllocator {
  constructor(
    private start = 4100,
    private blockSize = 10,
    private maxBlocks = 500,
    private probe: PortProbe = isPortFree,
  ) {}

  async allocate(reserved: PortBlock[]): Promise<PortBlock> {
    const taken = new Set(reserved.map((b) => b.base));
    for (let i = 0; i < this.maxBlocks; i++) {
      const base = this.start + i * this.blockSize;
      if (taken.has(base)) continue;
      const ports = Array.from({ length: this.blockSize }, (_, k) => base + k);
      const free = await Promise.all(ports.map((p) => this.probe(p)));
      if (free.every(Boolean)) return { base, ports };
    }
    throw new Error("No free port block available");
  }
}

export function portEnv(block: PortBlock): Record<string, string> {
  const env: Record<string, string> = { PORT: String(block.ports[0]) };
  block.ports.forEach((p, i) => (env[`OCTAVE_PORT_${i}`] = String(p)));
  return env;
}

export function renderEnvFile(env: Record<string, string>): string {
  return (
    "# Generated by Octave. Ports reserved for this workspace only.\n" +
    Object.entries(env).map(([k, v]) => `${k}=${v}`).join("\n") +
    "\n"
  );
}
